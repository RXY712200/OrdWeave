exe = str(pathlib.Path(sys.argv[1]).resolve())
vectors = json.loads(pathlib.Path(sys.argv[2]).read_text())
be = lambda n, width: n.to_bytes(width, 'big')
sha = lambda b: hashlib.sha256(b).digest()
ID = bytes(range(16))

def manifest(version=3):
    b = b'OWMAN003' + be(version,4) + be(96,4) + ID + be(67108864,8) + be(16777216,8) + bytes(16)
    return b + sha(b)

def segment(seq=1, first=1, prev=bytes(32), identity=ID):
    b = b'OWWAL003' + be(3,4) + be(128,4) + identity + be(seq,8) + be(first,8) + prev + bytes(16)
    return b + sha(b)

def frame(op=1, revision=1, payload=be(1,8), prev=bytes(32)):
    b = b'OWTXN003' + be(136+len(payload),4) + be(3,2) + be(op,2) + be(revision,8) + be(len(payload),4) + bytes(4) + prev
    b += sha(b)
    b += payload
    return b + sha(b) + b'COMMIT03'

assert manifest().hex() == vectors['manifest']
assert segment().hex() == vectors['segment1']
assert frame().hex() == vectors['record1_revision1']

def check(root, expected, revision=None):
    p = subprocess.run([exe,'probe',str(root)],capture_output=True,text=True)
    assert p.returncode == expected, (root.name,p.returncode,p.stdout,p.stderr,expected)
    if revision is not None:
        assert p.stdout.strip() == str(revision), (p.stdout,revision)

